-- Hotel Booking System - schema v2 (MySQL 8)
-- Changes from the proposal: settings table (hotel name, tax rate) and tax fields on reservations.

CREATE DATABASE IF NOT EXISTS hotel_booking CHARACTER SET utf8mb4;
USE hotel_booking;

CREATE TABLE settings (
    id          TINYINT PRIMARY KEY DEFAULT 1,          -- always one row
    hotel_name  VARCHAR(100)  NOT NULL,
    tax_rate    DECIMAL(5,4)  NOT NULL,                  -- 0.0500 = 5%
    CONSTRAINT one_row CHECK (id = 1),
    CONSTRAINT tax_range CHECK (tax_rate >= 0 AND tax_rate <= 1)
);

CREATE TABLE admins (
    admin_id       INT AUTO_INCREMENT PRIMARY KEY,
    username       VARCHAR(50)  NOT NULL UNIQUE,
    password_hash  VARCHAR(255) NOT NULL                 -- hash only, never plain text
);

CREATE TABLE customers (
    customer_id  INT AUTO_INCREMENT PRIMARY KEY,
    full_name    VARCHAR(100) NOT NULL,
    email        VARCHAR(150) NOT NULL,
    phone        VARCHAR(30),
    INDEX idx_customer_email (email)                      -- My Bookings looks up by email
);

CREATE TABLE rooms (
    room_id          INT AUTO_INCREMENT PRIMARY KEY,
    room_number      VARCHAR(10)  NOT NULL UNIQUE,
    room_type        VARCHAR(30)  NOT NULL,               -- Standard, Deluxe, Suite
    capacity         INT          NOT NULL CHECK (capacity >= 1),
    price_per_night  DECIMAL(10,2) NOT NULL CHECK (price_per_night > 0),
    amenities        VARCHAR(255),
    status           ENUM('InService','OutOfService') NOT NULL DEFAULT 'InService',
    image_path       VARCHAR(255)
);

CREATE TABLE reservations (
    reservation_id  INT AUTO_INCREMENT PRIMARY KEY,
    customer_id     INT NOT NULL,
    room_id         INT NOT NULL,
    check_in        DATE NOT NULL,
    check_out       DATE NOT NULL,
    guests          INT  NOT NULL CHECK (guests >= 1),
    subtotal        DECIMAL(10,2) NOT NULL,               -- nights x price_per_night
    tax_rate        DECIMAL(5,4)  NOT NULL,               -- rate at booking time (snapshot)
    tax_amount      DECIMAL(10,2) NOT NULL,
    total_price     DECIMAL(10,2) NOT NULL,               -- subtotal + tax_amount
    status          ENUM('Confirmed','Cancelled') NOT NULL DEFAULT 'Confirmed',
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_res_customer FOREIGN KEY (customer_id) REFERENCES customers(customer_id),
    CONSTRAINT fk_res_room     FOREIGN KEY (room_id)     REFERENCES rooms(room_id),
    CONSTRAINT dates_valid CHECK (check_out > check_in),
    INDEX idx_overlap (room_id, status, check_in, check_out),   -- availability query
    INDEX idx_res_dates (check_in, check_out)                    -- statistics / revenue
);

